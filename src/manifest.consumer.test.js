import { afterAll, beforeAll, describe, expect, it } from 'vitest'
import { execFileSync } from 'node:child_process'
import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  symlinkSync,
  writeFileSync,
} from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join, resolve } from 'node:path'
import { demos } from './manifest.js'
import { FIELDS, parseFrontMatter } from '../scripts/manifest.mjs'
import pkg from '../package.json' with { type: 'json' }
import { findBrowser, openPage } from './test/browser.js'

// The consumer test (src/manifest.spec.md, tests.3): the package as `npm pack`
// ships it, installed by file link into a minimal consumer laid out the way
// the site is, which imports `cocoon-ai/demos` from its own node_modules,
// reads every entry's doc from the package's docs folder with the manifest's
// reader, and renders every entry with its doc on one page in the harness's
// Chromium. The fit test proves the contract from the source tree; this one
// proves it from the packed files: the `files` list, the exports map, the
// externals resolving to the consumer's own react, three and fiber, the docs
// reaching the consumer's build. Measured 2026-10-19 on Linux.

const ROOT = resolve(import.meta.dirname, '..')
const browser = findBrowser()
const RECT = { height: 160, gap: 16, doc: 96, width: 288, x: 16 }
const PAGE = {
  width: 320,
  height: RECT.gap + demos.length * (RECT.doc + RECT.height + RECT.gap),
}
/** The peers a consumer provides, linked from this tree's install as the site's own install holds them. */
const PEERS = Object.keys(pkg.peerDependencies)

/** The consumer's page, generated with the docs' bodies inlined the way a static build inlines what it read. */
const pageSource = (
  bodies,
) => `// generated by src/manifest.consumer.test.js: the consumer's page, from the package
import { useEffect } from 'react'
import { createRoot } from 'react-dom/client'
import { Canvas, useThree } from '@react-three/fiber'
import tunnel from 'tunnel-rat'
import { WebGPURenderer } from 'three/webgpu'
import { demos } from 'cocoon-ai/demos'

const t = tunnel()
const DOCS = ${JSON.stringify(bodies)}
const RECT = ${JSON.stringify(RECT)}
const state = Object.fromEntries(
  demos.map((e) => [e.name, { readyAt: null, handle: null }]),
)

function Facts() {
  const scene = useThree((s) => s.scene)
  useEffect(() => {
    window.__consumer = {
      manifest: () =>
        demos.map((e) => ({
          name: e.name,
          title: e.title,
          summary: e.summary,
          since: e.since,
          credits: [...e.credits],
          tags: [...e.tags],
          doc: e.doc,
          scene: e.scene,
          component: typeof e.component,
          demo: typeof e.demo,
          schema: typeof e.schema,
          effects: Array.isArray(e.effects),
        })),
      entries: () =>
        demos.map((e) => {
          const el = document.getElementById('entry-' + e.name)
          const stage = el?.querySelector('.cocoon-demo__stage')
          const h = state[e.name].handle
          return {
            name: e.name,
            scene: e.scene,
            mounted: !!el?.querySelector('.cocoon-demo'),
            heading: el?.querySelector('h1')?.textContent ?? null,
            docChars: el?.querySelector('pre.doc')?.textContent.length ?? 0,
            loader: !!stage?.querySelector(':scope > .loader'),
            readyMs:
              state[e.name].readyAt === null
                ? null
                : state[e.name].readyAt - window.__mountedAt,
            handle: h
              ? { root: !!h.root?.isGroup, materials: h.materials.length, compile: typeof h.compile }
              : null,
          }
        }),
      sceneChildren: () => scene.children.length,
    }
    window.__ready = true
  }, [scene])
  return null
}

function Page() {
  return (
    <>
      <Canvas
        style={{ position: 'fixed', inset: 0 }}
        camera={{ position: [0, 0, 5], fov: 50 }}
        frameloop='always'
        dpr={1}
        gl={async (props) => {
          const renderer = new WebGPURenderer({ ...props, forceWebGL: false })
          await renderer.init()
          return renderer
        }}
      >
        <t.Out />
        <Facts />
      </Canvas>
      {demos.map((entry, i) => {
        const Demo = entry.demo
        const top = RECT.gap / 2 + i * (RECT.doc + RECT.height + RECT.gap)
        return (
          <section
            key={entry.name}
            id={'entry-' + entry.name}
            style={{ position: 'absolute', left: RECT.x, top, width: RECT.width }}
          >
            <div style={{ height: RECT.doc, overflow: 'hidden' }}>
              <h1>{entry.title}</h1>
              <p>{entry.summary}</p>
              <pre className='doc'>{DOCS[entry.name]}</pre>
            </div>
            <div style={{ position: 'relative', width: RECT.width, height: RECT.height }}>
              <Demo
                {...(entry.scene ? { tunnel: t } : {})}
                theme='site'
                demoContainerClass='site-demo'
                openSettings
                loader={<div className='loader'>loading</div>}
                onReady={() => {
                  state[entry.name].readyAt = performance.now()
                }}
                ref={(h) => {
                  state[entry.name].handle = h
                }}
              />
            </div>
          </section>
        )
      })}
    </>
  )
}

window.__mountedAt = performance.now()
document.getElementById('root').style.cssText =
  'position:fixed;inset:0;width:auto;height:auto'
createRoot(document.getElementById('root')).render(<Page />)
`

let site
let work
let shipped
let consumerPkg
let docs
const entries = () => site.evaluate(() => window.__consumer.entries())

describe.skipIf(!browser)(
  'the package consumed by file link from a minimal consumer',
  () => {
    beforeAll(async () => {
      work = mkdtempSync(join(tmpdir(), 'cocoon-consumer-'))
      // 1. the library built as `npm run build` builds it, in a child process so vitest's
      // NODE_ENV=test does not pick the dev JSX runtime, then packed as npm packs it: only what
      // package.json's `files` names, with the tarball's own file list as the record
      execFileSync('npm', ['run', 'build', '--silent'], {
        cwd: ROOT,
        env: { ...process.env, NODE_ENV: 'production' },
        stdio: 'pipe',
      })
      const packed = JSON.parse(
        execFileSync(
          'npm',
          ['pack', '--json', '--silent', '--pack-destination', work],
          { cwd: ROOT, stdio: ['ignore', 'pipe', 'ignore'] },
        ).toString(),
      )
      const tarball = join(work, packed[0].filename)
      shipped = packed[0].files.map((f) => f.path)
      // 2. the consumer: a package depending on cocoon-ai by file link, the tarball unpacked
      // into its node_modules as `npm install` unpacks one, the peers linked to this tree's
      // install as the site's own install holds them (one react, one three, one fiber)
      const consumer = join(work, 'consumer')
      consumerPkg = join(consumer, 'node_modules', 'cocoon-ai')
      mkdirSync(consumerPkg, { recursive: true })
      writeFileSync(
        join(consumer, 'package.json'),
        JSON.stringify(
          {
            name: 'consumer',
            private: true,
            type: 'module',
            dependencies: { 'cocoon-ai': `file:${tarball}` },
          },
          null,
          2,
        ),
      )
      execFileSync(
        'tar',
        ['-xzf', tarball, '-C', consumerPkg, '--strip-components=1'],
        { stdio: 'pipe' },
      )
      for (const name of PEERS) {
        const real = join(ROOT, 'node_modules', name)
        if (!existsSync(real)) continue
        const link = join(consumer, 'node_modules', name)
        mkdirSync(dirname(link), { recursive: true })
        symlinkSync(real, link, 'dir')
      }
      // 3. the docs, read from the package's folder the way a consumer's build copies them,
      // parsed with the manifest's own reader (docs.6, docs.7)
      docs = Object.fromEntries(
        demos.map((e) => [
          e.name,
          parseFrontMatter(
            readFileSync(join(consumerPkg, e.doc), 'utf8'),
            e.doc,
          ),
        ]),
      )
      // 4. the page: the consumer's shape, every entry with its doc and its demo, from the package
      const entry = join(consumer, 'page.jsx')
      writeFileSync(
        entry,
        pageSource(
          Object.fromEntries(
            Object.entries(docs).map(([name, d]) => [name, d.body]),
          ),
        ),
      )
      site = await openPage(entry, PAGE)
      await site.page.waitForFunction(
        () =>
          window.__consumer
            .entries()
            .every((e) => !e.scene || e.readyMs !== null),
        { timeout: 60_000 },
      )
    }, 180_000)
    afterAll(async () => {
      if (site) await site.close()
      if (work) rmSync(work, { recursive: true, force: true })
    })

    it('files: the tarball ships dist, every doc the manifest names and package.json, and nothing from the source tree', () => {
      for (const p of [
        'package.json',
        'dist/index.js',
        'dist/demos.js',
        ...demos.map((e) => e.doc),
      ])
        expect(shipped, `${p} is not in the tarball`).toContain(p)
      expect(
        shipped.filter(
          (p) =>
            p.startsWith('src/') ||
            p.startsWith('scripts/') ||
            p.startsWith('assets/') ||
            p.includes('.test.'),
        ),
      ).toEqual([])
      expect(
        JSON.parse(readFileSync(join(consumerPkg, 'package.json'), 'utf8'))
          .exports['./demos'],
      ).toBeDefined()
    })

    it('manifest: the packed manifest carries the same entries and data as the source tree', async () => {
      const packed = await site.evaluate(() => window.__consumer.manifest())
      expect(packed).toEqual(
        demos.map((e) => ({
          name: e.name,
          title: e.title,
          summary: e.summary,
          since: e.since,
          credits: [...e.credits],
          tags: [...e.tags],
          doc: e.doc,
          scene: e.scene,
          component: 'function',
          demo: 'function',
          schema: 'object',
          effects: true,
        })),
      )
    })

    it("docs: every entry's doc is in the package, its front matter equals the entry, and its body reaches the page", async () => {
      const facts = await entries()
      for (const e of demos) {
        const { data, body } = docs[e.name]
        for (const field of FIELDS)
          expect(data[field], `${e.doc}: ${field}`).toEqual(e[field])
        const fact = facts.find((f) => f.name === e.name)
        expect(fact.heading, `${e.name}: the doc page's head`).toBe(e.title)
        expect(fact.docChars, `${e.name}: the doc's body`).toBe(body.length)
      }
    })

    it("demos: every entry mounts from the packed bundle, a scene demo reports ready on the consumer's react, three and fiber, and no page error", async () => {
      const facts = await entries()
      expect(facts.map((f) => f.name)).toEqual(demos.map((e) => e.name))
      for (const f of facts) {
        expect(f.mounted, `${f.name} did not mount`).toBe(true)
        if (!f.scene) continue
        expect(f.readyMs, `${f.name} never reported ready`).not.toBeNull()
        expect(f.loader, `${f.name}'s loader is still in the stage`).toBe(false)
        expect(f.handle).toEqual({
          root: true,
          materials: expect.any(Number),
          compile: 'function',
        })
      }
      expect(site.errors).toEqual([])
    })
  },
)
